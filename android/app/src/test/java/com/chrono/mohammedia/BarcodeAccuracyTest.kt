package com.chrono.mohammedia

import com.chrono.mohammedia.ui.scanner.CameraXScannerHelper
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class BarcodeAccuracyTest {

    @Test
    fun testCleanBarcodeValue_removesSymbologyPrefixesAndArtifacts() {
        // GS1 / AIM prefixes
        assertEquals("PP501040424MA", CameraXScannerHelper.cleanBarcodeValue("]C1PP501040424MA"))
        assertEquals("LD644278718MA", CameraXScannerHelper.cleanBarcodeValue("]e0LD644278718MA"))
        assertEquals("LG095266299MA", CameraXScannerHelper.cleanBarcodeValue("]d2LG095266299MA"))

        // Code 39 framing characters
        assertEquals("LD644278718MA", CameraXScannerHelper.cleanBarcodeValue("*LD644278718MA*"))
        assertEquals("CD1234567890", CameraXScannerHelper.cleanBarcodeValue("#CD1234567890#"))

        // Internal whitespace
        assertEquals("PP501040424MA", CameraXScannerHelper.cleanBarcodeValue("PP 501040424 MA"))
        assertEquals("LD644278718MA", CameraXScannerHelper.cleanBarcodeValue("  LD  644278718 MA  "))

        // ASCII control chars (CR, LF, GS \u001D)
        assertEquals("LG095266299MA", CameraXScannerHelper.cleanBarcodeValue("LG095266299MA\r\n\u001D"))
    }

    @Test
    fun testIsMoroccanShippingCode_detectsAllStandardFormats() {
        // UPU S10 Barid Al-Maghrib / Amana codes
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("LD644278718MA"))
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("LG095266299MA"))
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("PP501040424MA"))
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("QB123456789MA"))
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("EY987654321MA"))
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("CP123456789MA"))

        // Chronodiali Hub codes
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("CD0123456789"))
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("CD99988877"))

        // Shipsy / Hub formats
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("LCWK-MOH-12345"))
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("SHP-98765432"))
        assertTrue(CameraXScannerHelper.isMoroccanShippingCode("HUB-CASABLANCA"))

        // Non-shipping codes should be false
        assertFalse(CameraXScannerHelper.isMoroccanShippingCode("123456"))
        assertFalse(CameraXScannerHelper.isMoroccanShippingCode("RANDOMTEXT"))
    }

    @Test
    fun testIsValidParcelBarcode_rejectsPhantomNumbers() {
        // Short phantom numbers generated by ITF or noisy decodes MUST be rejected
        assertFalse("6-digit phantom should be rejected", CameraXScannerHelper.isValidParcelBarcode("829104"))
        assertFalse("7-digit phantom should be rejected", CameraXScannerHelper.isValidParcelBarcode("1029384"))
        assertFalse("5-digit phantom should be rejected", CameraXScannerHelper.isValidParcelBarcode("12345"))
        assertFalse("Short text should be rejected", CameraXScannerHelper.isValidParcelBarcode("TEST"))

        // Repetitive or dummy numbers MUST be rejected
        assertFalse("All zeros should be rejected", CameraXScannerHelper.isValidParcelBarcode("0000000000"))
        assertFalse("All ones should be rejected", CameraXScannerHelper.isValidParcelBarcode("1111111111"))

        // Plain words without parcel digits MUST be rejected
        assertFalse("Plain word should be rejected", CameraXScannerHelper.isValidParcelBarcode("CHRONODIALI"))
        assertFalse("Header text should be rejected", CameraXScannerHelper.isValidParcelBarcode("ACCUSEFUTURAMA"))
    }

    @Test
    fun testIsValidParcelBarcode_acceptsLegitimateParcels() {
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("LD644278718MA"))
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("LG095266299MA"))
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("PP501040424MA"))
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("CD0123456789"))
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("LCWK-CAS-9988"))
        // Valid courier alphanumeric tracking
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("CTM12345678"))
        // Valid 10-digit numeric tracking
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("3012948291"))
        // Valid 13-digit barcode
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("2000001234567"))
    }

    @Test
    fun testExpectedCodes_prioritizationAndMatching() {
        val expected = setOf("LG095266299MA", "LD644278718MA", "LCWK-001")

        // Matches expected
        assertTrue(CameraXScannerHelper.isCodeInExpectedSet("LG095266299MA", expected))
        assertTrue(CameraXScannerHelper.isCodeInExpectedSet("lg095266299ma", expected))
        assertTrue(CameraXScannerHelper.isCodeInExpectedSet("LCWK001", expected))

        // Not in expected
        assertFalse(CameraXScannerHelper.isCodeInExpectedSet("UNKNOWN9999MA", expected))

        // In expected set, isValidParcelBarcode returns true
        assertTrue(CameraXScannerHelper.isValidParcelBarcode("LCWK-001", expected))
    }
}

